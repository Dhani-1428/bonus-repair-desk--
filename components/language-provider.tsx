const LanguageContext = createContext<LanguageContextValue | undefined>(undefined)

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>("en")

  useEffect(() => {
    if (typeof window === "undefined") return
    const stored = window.localStorage.getItem("language")
    const validLanguages: Language[] = ["en", "pt", "de", "fr", "es", "it", "nl", "pl", "ro", "el", "cs", "hu", "sv", "fi", "da", "bg", "hr", "sk", "sl", "lt", "lv", "et", "ga", "mt", "ur", "pa", "hi"]
    if (stored && validLanguages.includes(stored as Language)) {
      setLanguageState(stored as Language)
    }
  }, [])

  const setLanguage = (lang: Language) => {
    setLanguageState(lang)
    if (typeof window !== "undefined") {
      window.localStorage.setItem("language", lang)
    }
  }

  const t = useMemo(() => {
    return (key: string) => {
      const current = translations[language][key]
      if (current !== undefined) return current
      const fallback = translations.en[key]
      return fallback ?? key
    }
  }, [language])

  const value = useMemo(() => ({
    language,
    setLanguage,
    t
  }), [language, t])

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  )
}

export function useTranslation() {
  const ctx = useContext(LanguageContext)
  if (!ctx) {
    throw new Error("useTranslation must be used within a LanguageProvider")
  }
  return ctx
}

